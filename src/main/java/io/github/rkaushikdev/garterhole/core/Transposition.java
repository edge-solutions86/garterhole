package io.github.rkaushikdev.garterhole.core;

import io.github.rkaushikdev.garterhole.util.Guards;
import java.util.ArrayList;
import java.util.List;

/**
 * Rows compose. Applying one row to another is how a course head is stepped on
 * to the next, how a call is applied to a lead end, and how a part end is raised
 * to a power to give the part heads of a composition.
 *
 * <p>The convention here is the one used in the printed literature: in
 * {@code a} by {@code b} the bells of {@code a} are read in the order that
 * {@code b} gives, so place {@code i} of the answer holds the bell that
 * {@code a} had in the place {@code b} names.
 */
public final class Transposition {

    private Transposition() {}

    /**
     * @param left the row whose bells are read
     * @param right the row giving the order they are read in
     * @return the composed row
     * @throws IllegalArgumentException when a row is missing or the stages differ
     */
    public static Row transpose(Row left, Row right) {
        requireSameStage(left, right);
        int[] bells = new int[left.stage()];
        int[] leftBells = left.toArray();
        int[] rightBells = right.toArray();
        for (int place = 0; place < bells.length; place += 1) {
            bells[place] = leftBells[rightBells[place] - 1];
        }
        return new Row(bells);
    }

    /**
     * The row that undoes another. Transposing a row by its inverse gives rounds.
     *
     * @param row a row
     * @return its inverse
     */
    public static Row inverse(Row row) {
        requireRow(row, "row");
        int[] source = row.toArray();
        int[] bells = new int[source.length];
        for (int place = 0; place < source.length; place += 1) {
            bells[source[place] - 1] = place + 1;
        }
        return new Row(bells);
    }

    /**
     * The row that takes {@code from} to {@code to}, so that transposing
     * {@code from} by the answer gives {@code to}. This is how a calling
     * position works out which transposition a call actually applied.
     *
     * @param from the row before
     * @param to the row after
     * @return the transposition between them
     */
    public static Row permutationBetween(Row from, Row to) {
        requireSameStage(from, to);
        return transpose(inverse(from), to);
    }

    /**
     * Apply a row to itself repeatedly. A negative exponent applies the
     * inverse, and zero gives rounds, which keeps the usual index laws working.
     *
     * @param row a row
     * @param exponent how many times to apply it
     * @return the row raised to the power
     */
    public static Row power(Row row, int exponent) {
        requireRow(row, "row");
        Row base = exponent < 0 ? inverse(row) : row;
        Row result = Row.rounds(row.stage());
        for (int step = 0; step < Math.abs(exponent); step += 1) {
            result = transpose(result, base);
        }
        return result;
    }

    /**
     * How many times a row has to be applied to itself to come back to rounds.
     * It is the number of parts a composition with that part end will have.
     *
     * @param row a row
     * @return its order
     */
    public static int order(Row row) {
        requireRow(row, "row");
        return Cycles.orderOf(row);
    }

    /**
     * Every row reachable by applying a row to itself, starting at rounds and
     * stopping when it comes back: the group generated by a single row.
     *
     * @param row a row
     * @return the group, rounds first
     */
    public static List<Row> cyclicGroup(Row row) {
        requireRow(row, "row");
        List<Row> members = new ArrayList<>();
        members.add(Row.rounds(row.stage()));
        Row current = row;
        while (!current.isRounds()) {
            members.add(current);
            current = transpose(current, row);
        }
        return List.copyOf(members);
    }

    private static void requireRow(Row row, String label) {
        Guards.present(row, label + " must be a Row");
    }

    private static void requireSameStage(Row left, Row right) {
        requireRow(left, "the left row");
        requireRow(right, "the right row");
        if (left.stage() != right.stage()) {
            throw new IllegalArgumentException(
                    "cannot combine a row of " + left.stage() + " with a row of " + right.stage());
        }
    }
}
