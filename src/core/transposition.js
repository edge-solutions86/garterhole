import { Row, rounds } from './row.js';
import { assertInteger } from '../util/assert.js';
import { orderOf } from './cycles.js';

/**
 * Rows compose. Applying one row to another is how a course head is stepped on
 * to the next, how a call is applied to a lead end, and how a part end is
 * raised to a power to give the part heads of a composition.
 *
 * The convention here is the one used in the printed literature: in `a` by `b`
 * the bells of `a` are read in the order that `b` gives, so place `i` of the
 * answer holds the bell that `a` had in the place `b` names.
 */

/**
 * @param {Row} left
 * @param {Row} right
 * @returns {Row}
 */
export function transpose(left, right) {
  assertSameStage(left, right);
  const bells = new Array(left.stage);
  for (let place = 0; place < left.stage; place += 1) {
    bells[place] = left.bells[right.bells[place] - 1];
  }
  return new Row(bells);
}

/**
 * The row that undoes another. Transposing a row by its inverse gives rounds.
 *
 * @param {Row} row
 * @returns {Row}
 */
export function inverse(row) {
  assertRow(row, 'row');
  const bells = new Array(row.stage);
  for (let place = 0; place < row.stage; place += 1) {
    bells[row.bells[place] - 1] = place + 1;
  }
  return new Row(bells);
}

/**
 * The row that takes `from` to `to`, so that transposing `from` by the answer
 * gives `to`. This is how a calling position works out which transposition a
 * call actually applied.
 *
 * @param {Row} from
 * @param {Row} to
 * @returns {Row}
 */
export function permutationBetween(from, to) {
  assertSameStage(from, to);
  return transpose(inverse(from), to);
}

/**
 * Apply a row to itself repeatedly. A negative exponent applies the inverse,
 * and zero gives rounds, which keeps the usual index laws working.
 *
 * @param {Row} row
 * @param {number} exponent
 * @returns {Row}
 */
export function power(row, exponent) {
  assertRow(row, 'row');
  assertInteger(exponent, 'exponent');
  const base = exponent < 0 ? inverse(row) : row;
  let result = rounds(row.stage);
  for (let i = 0; i < Math.abs(exponent); i += 1) {
    result = transpose(result, base);
  }
  return result;
}

/**
 * How many times a row has to be applied to itself to come back to rounds. It
 * is the number of parts a composition with that part end will have.
 *
 * @param {Row} row
 * @returns {number}
 */
export function order(row) {
  assertRow(row, 'row');
  return orderOf(row);
}

/**
 * Every row reachable by applying a row to itself, starting at rounds and
 * stopping when it comes back. The group generated by a single row.
 *
 * @param {Row} row
 * @returns {Row[]}
 */
export function cyclicGroup(row) {
  assertRow(row, 'row');
  const members = [rounds(row.stage)];
  let current = row;
  while (!current.isRounds()) {
    members.push(current);
    current = transpose(current, row);
  }
  return members;
}

/**
 * @param {unknown} value
 * @param {string} label
 */
function assertRow(value, label) {
  if (!(value instanceof Row)) {
    throw new TypeError(`${label} must be a Row`);
  }
}

/**
 * @param {Row} left
 * @param {Row} right
 */
function assertSameStage(left, right) {
  assertRow(left, 'the left row');
  assertRow(right, 'the right row');
  if (left.stage !== right.stage) {
    throw new RangeError(`cannot combine a row of ${left.stage} with a row of ${right.stage}`);
  }
}
